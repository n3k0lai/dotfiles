# fdroid-repo setup: runs as the fdroid service user before every ingest.
# Idempotent. Creates the repo signing keystore once (0600, never in the
# nix store) and rewrites config.yml from the module's settings.
#
# Env (set by the NixOS module): DATA_DIR REPO_URL REPO_NAME REPO_DESC
#   ARCHIVE_OLDER KEY_DNAME
set -euo pipefail
umask 077

cd "$DATA_DIR"
mkdir -p secrets incoming rejected metadata
mkdir -p -m 0755 repo archive

alias_name="repokey"
if [ ! -s secrets/keystore.p12 ]; then
  if [ -e secrets/keystore.p12 ] || [ -s secrets/keystore.env ]; then
    echo "fdroid-repo: refusing to regenerate: partial key material in $DATA_DIR/secrets" >&2
    exit 1
  fi
  echo "fdroid-repo: first run, generating the repo signing key"
  pass="$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')"
  printf 'KEYSTORE_PASS=%s\n' "$pass" > secrets/keystore.env.tmp
  keytool -genkeypair -noprompt \
    -keystore secrets/keystore.p12.tmp -storetype PKCS12 \
    -alias "$alias_name" -keyalg RSA -keysize 4096 -sigalg SHA256withRSA \
    -validity 36500 -dname "$KEY_DNAME" \
    -storepass "$pass" -keypass "$pass" >/dev/null 2>&1
  mv secrets/keystore.env.tmp secrets/keystore.env
  mv secrets/keystore.p12.tmp secrets/keystore.p12
fi
chmod 0700 secrets
chmod 0600 secrets/keystore.p12 secrets/keystore.env

# shellcheck disable=SC1091
. secrets/keystore.env

json() { jq -Rn --arg v "$1" '$v'; }  # JSON string == valid YAML scalar

cat > config.yml.tmp <<YML
# Generated by fdroid-repo setup on every run. Edit the NixOS module instead.
repo_url: $(json "$REPO_URL")
repo_name: $(json "$REPO_NAME")
repo_description: $(json "$REPO_DESC")
archive_url: $(json "${REPO_URL%/repo}/archive")
archive_name: $(json "$REPO_NAME (archive)")
archive_description: $(json "Older versions of $REPO_NAME apps.")
archive_older: $ARCHIVE_OLDER
keystore: $(json "$DATA_DIR/secrets/keystore.p12")
repo_keyalias: $alias_name
keystorepass: $(json "$KEYSTORE_PASS")
keypass: $(json "$KEYSTORE_PASS")
keydname: $(json "$KEY_DNAME")
apksigner: $(json "$(command -v apksigner)")
jarsigner: $(json "$(command -v jarsigner)")
keytool: $(json "$(command -v keytool)")
make_current_version_link: false
YML
chmod 0600 config.yml.tmp
mv config.yml.tmp config.yml

# Public fingerprint (not secret): what you type into Droid-ify.
fp="$(keytool -list -v -keystore secrets/keystore.p12 -storepass "$KEYSTORE_PASS" -alias "$alias_name" 2>/dev/null \
  | sed -n 's/^[[:space:]]*SHA256: //p' | tr -d ':' | tr 'A-F' 'a-f')"
if [ -n "$fp" ]; then
  umask 022
  printf '%s\n' "$fp" > FINGERPRINT
  printf '%s?fingerprint=%s\n' "$REPO_URL" "$fp" > SHARE_URL
fi
