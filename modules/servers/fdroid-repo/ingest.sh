# fdroid-repo ingest: runs as the fdroid service user.
# For each incoming/<pkg>_<vc>.json manifest with its APK:
#   1. sha256 of the APK matches the manifest
#   2. the APK's signing cert matches the pinned cert for that package
#   3. versionCode is higher than anything already in repo/ or archive/
# Good APKs move into repo/, the changelog lands in
# metadata/<pkg>/en-US/changelogs/<vc>.txt, then `fdroid update` signs and
# publishes the index. Bad ones go to rejected/ with a .reason file.
#
# Every outcome is also written to status/<pkg>_<vc> (world-readable), so the
# uploader can poll for "accepted" or "rejected: <reason>" over SSH.
#
# Env: DATA_DIR PINS_FILE ALLOW_UNPINNED KEEP_ARCHIVED MIN_FREE_MB [FORCE_UPDATE=1]
set -euo pipefail
umask 022
cd "$DATA_DIR"
mkdir -p incoming rejected metadata repo archive status
accepted=()

pkg_re='^[A-Za-z][A-Za-z0-9_]*(\.[A-Za-z0-9_]+)+$'
changed=0

reject() { # <base> <reason>
  local base="$1" reason="$2" ts
  ts="$(date +%Y%m%dT%H%M%S)"
  echo "fdroid-repo: REJECTED $base: $reason" >&2
  for f in "incoming/$base.apk" "incoming/$base.json"; do
    [ -e "$f" ] && mv "$f" "rejected/$ts-$(basename "$f")"
  done
  printf '%s\n' "$reason" > "rejected/$ts-$base.reason"
  printf 'rejected: %s\n' "$reason" > "status/$base"
}

max_published_vc() { # <pkg>
  local pkg="$1" max=0 f vc
  for f in repo/"${pkg}"_*.apk archive/"${pkg}"_*.apk; do
    [ -e "$f" ] || continue
    vc="${f##*_}"; vc="${vc%.apk}"
    [[ "$vc" =~ ^[0-9]+$ ]] && [ "$vc" -gt "$max" ] && max="$vc"
  done
  echo "$max"
}


for m in incoming/*.json; do
  [ -e "$m" ] || continue
  base="$(basename "$m" .json)"
  pkg="$(jq -er '.package' "$m" 2>/dev/null || true)"
  vc="$(jq -er '.versionCode' "$m" 2>/dev/null || true)"
  if ! [[ "$pkg" =~ $pkg_re ]] || ! [[ "$vc" =~ ^[0-9]+$ ]] || [ "$base" != "${pkg}_${vc}" ]; then
    reject "$base" "manifest invalid or does not match its file name"; continue
  fi
  apk="incoming/$base.apk"
  if [ ! -f "$apk" ]; then
    reject "$base" "manifest arrived without its APK"; continue
  fi

  want_sha="$(jq -r '.sha256' "$m")"
  got_sha="$(sha256sum "$apk" | cut -d' ' -f1)"
  if [ "$want_sha" != "$got_sha" ]; then
    reject "$base" "sha256 mismatch (manifest $want_sha, file $got_sha)"; continue
  fi

  if ! certs="$(apksigner verify --print-certs "$apk" 2>&1)"; then
    reject "$base" "apksigner verify failed: $(printf '%s' "$certs" | tail -n 3 | tr '\n' ' ')"; continue
  fi
  nsigners="$(printf '%s\n' "$certs" | grep -c '^Signer #[0-9]* certificate SHA-256 digest:' || true)"
  cert="$(printf '%s\n' "$certs" | sed -n 's/^Signer #1 certificate SHA-256 digest: //p' | tr 'A-F' 'a-f')"
  if [ "$nsigners" != 1 ] || [ -z "$cert" ]; then
    reject "$base" "expected exactly one signer, found $nsigners"; continue
  fi
  pin="$(jq -r --arg p "$pkg" '.[$p] // empty' "$PINS_FILE" | tr 'A-F' 'a-f')"
  if [ -n "$pin" ] && [ "$pin" != "$cert" ]; then
    reject "$base" "signing cert $cert does not match pinned $pin"; continue
  fi
  if [ -z "$pin" ] && [ "${ALLOW_UNPINNED:-0}" != 1 ]; then
    reject "$base" "no pinned cert for $pkg (add it to modules.servers.fdroid-repo.pins; cert is $cert)"; continue
  fi

  free_mb="$(df --output=avail -BM . | tail -n 1 | tr -dc '0-9')"
  apk_mb="$(( $(stat -c %s "$apk") / 1048576 + 1 ))"
  if [ "$(( free_mb - apk_mb ))" -lt "${MIN_FREE_MB:-1024}" ]; then
    reject "$base" "disk: only ${free_mb} MB free, keeping at least ${MIN_FREE_MB:-1024} MB"; continue
  fi

  last="$(max_published_vc "$pkg")"
  if [ "$vc" -le "$last" ]; then
    reject "$base" "versionCode $vc is not higher than published $last"; continue
  fi

  # Metadata: metadata/<pkg>/app.json is the source of truth (seeded from the
  # first manifest), rendered to metadata/<pkg>.yml every time. A Builds entry
  # per published versionCode lets fdroid attach each changelog as "What's new".
  # (Never add `disable:` to these: fdroid update deletes APKs of disabled builds.)
  mkdir -p "metadata/$pkg"
  appjson="metadata/$pkg/app.json"
  if [ ! -s "$appjson" ]; then
    jq '{name: (.name // ""), summary: (.summary // ""), author: (.author // ""),
         category: (.category // "Personal"), builds: []}' "$m" > "$appjson"
  fi
  jq --argjson vc "$vc" --arg vn "$(jq -r '.versionName // ""' "$m")" \
    '.builds = ([.builds[] | select(.versionCode != $vc)] + [{versionCode: $vc, versionName: $vn}]
                | sort_by(.versionCode) | .[-20:])' "$appjson" > "$appjson.tmp"
  mv "$appjson.tmp" "$appjson"
  jq -r '
    "# Generated by fdroid-repo ingest from \(input_filename). Edit app.json instead.",
    "Name: \(.name | tojson)",
    "Summary: \(.summary | tojson)",
    "AuthorName: \(.author | tojson)",
    "Categories:", "  - \(.category | tojson)",
    "",
    "Builds:",
    (.builds[] | "  - versionName: \(.versionName | tojson)", "    versionCode: \(.versionCode)",
                 "    commit: \"prebuilt\""),
    "",
    "CurrentVersion: \(.builds[-1].versionName | tojson)",
    "CurrentVersionCode: \(.builds[-1].versionCode)"' "$appjson" > "metadata/$pkg.yml"

  changelog="$(jq -r '.changelog // ""' "$m")"
  if [ -n "$changelog" ]; then
    mkdir -p "metadata/$pkg/en-US/changelogs"
    printf '%s\n' "$changelog" > "metadata/$pkg/en-US/changelogs/$vc.txt"
  fi

  mv "$apk" "repo/$base.apk"
  mv "$m" "metadata/$pkg/last-manifest.json"
  echo "fdroid-repo: accepted $pkg versionCode $vc (cert $cert)"
  printf 'publishing\n' > "status/$base"
  accepted+=("$base")
  changed=1
done

# Stray APKs whose manifest never came: drop after a day.
find incoming -maxdepth 1 -type f -name '*.apk' -mmin +1440 -print -delete || true

[ -e repo/index-v2.json ] || FORCE_UPDATE=1   # first run: publish an empty, addable repo
[ "$changed" = 1 ] || [ "${FORCE_UPDATE:-0}" = 1 ] || exit 0

fdroid update --create-metadata

# Keep only the newest KEEP_ARCHIVED APKs per package in archive/.
# (repo/ itself holds `archive_older` versions per app; fdroid moves the rest.)
before="$(find archive -maxdepth 1 -name '*.apk' | wc -l)"
for pkg in $(find archive -maxdepth 1 -name '*_*.apk' -printf '%f\n' | sed 's/_[0-9]*\.apk$//' | sort -u); do
  find archive -maxdepth 1 -name "${pkg}_*.apk" -printf '%f\n' |
    sed -n "s/^${pkg//./\\.}_\([0-9]*\)\.apk$/\1/p" | sort -rn |
    tail -n +"$((KEEP_ARCHIVED + 1))" |
    while read -r old; do
      echo "fdroid-repo: pruning archive/${pkg}_${old}.apk"
      rm -f "archive/${pkg}_${old}.apk"
    done
done
after="$(find archive -maxdepth 1 -name '*.apk' | wc -l)"
if [ "$after" != "$before" ]; then
  fdroid update
fi
date -Is > LAST_PUBLISH
for b in "${accepted[@]}"; do printf 'accepted %s\n' "$(date -Is)" > "status/$b"; done
# Status files are only for the uploader to poll; keep two weeks.
find status -maxdepth 1 -type f -mtime +14 -delete || true
